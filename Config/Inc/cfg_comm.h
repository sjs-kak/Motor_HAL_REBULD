#ifndef CFG_COMM_H
#define CFG_COMM_H

/* ============================================================================
 * 串口链路参数（与上位机通信的物理层）
 *
 * 这里只放"时序/长度"这类链路层常量；
 * 帧怎么组、命令怎么解释，仍然归 Service/App，不要往这里塞语义。
 * ============================================================================ */

/* 单次阻塞发送的超时（ms）。
 *
 * 为什么必须有上限：
 *   LOG() / 协议回包走的是阻塞发送（HAL_UART_Transmit 等 TC 标志）。
 *   如果 TC/TXE 一直不来 —— 电平转换板接错、TX 被拉低、收发器坏了 ——
 *   无超时（HAL_MAX_DELAY）的发送会把**主循环永久卡死**：
 *   主循环停转 = Motion_Tick() 不再执行 = 车会一直转下去。
 *   这正是"指令全失效 + 车还在跑"那类故障的形态。
 *
 *   宁可丢掉几个字节的日志，也绝不能让主循环停在发送里。
 *
 * 取值依据：115200 8N1 下 1 字节 ≈ 87 µs，5 ms 足够发约 57 字节，
 *   比任何一条回包（最长约 40 字节）都宽裕，又不至于让人感觉到卡顿。 */
#define CFG_UART_TX_TIMEOUT_MS   5

/* 接收通道数（按 Instance 分发的上限）。
 *
 * 现在只用 1 路（USART1 接上位机/无线调试器）；
 * 留 2 路是为了以后加相机串口（C1-C5 里会用到）时不用改代码结构：
 * 每路各自持有 1 字节暂存、自己的回调和自己的"已武装"标志，
 * 中断回调按 Instance 查表分发，互不抢占、互不丢字节。
 *
 * 每个通道占约 16 字节 RAM，加一路的代价可以忽略。 */
#define CFG_UART_RX_CHANNELS     2

#endif /* CFG_COMM_H */
