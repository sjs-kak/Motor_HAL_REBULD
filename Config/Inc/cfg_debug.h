#ifndef CFG_DEBUG_H
#define CFG_DEBUG_H

/* ============================================================================
 * 调试开关（默认全关，不参与正常固件行为）
 * ============================================================================
 *
 * 为什么需要这个文件：
 *   本项目调试用的是 STM32Cube 的 GDB 适配器（stgdbtarget），它的调试控制台
 *   对 `call` 求值有一个硬性要求 —— 必须有一个"选中的栈帧"(frameId)，
 *   否则一律报 "Evaluation of expression without frameId is not supported"。
 *   现场很难稳定满足。所以留一条**完全绕开调试器 call** 的路：
 *   改一个数字 → 重新编译 → F5，上电自动执行那一个动作。
 *
 * 用法：
 *   1) 把下面的 CFG_DEBUG_AUTOTEST 改成你想要的编号；
 *   2) 重新编译（tools/build.ps1）并 F5；
 *   3) 调试结束后**必须改回 0**。开着它上电就会动电机。
 *
 * 编号表（全部受 Motion_Clamp 限幅，最大 1200 Hz）：
 *   0   关闭（默认）
 *   1   Motion_Drive(1200, 0)        加速到 1200 并保持，**不会自己停**
 *   2   Motion_Drive(1200, 3000)     跑 1.2 s 加速 + 3 s 保持，**然后平滑停**
 *   3   Motion_Steer(600, -600, 3000) 原地左转 3 s（差速 200%），**然后平滑停**
 *   4   Motion_Demo()                六段演示：前进→右转→回正→前进→倒车→停
 *   5   Motion_Drive(2500, 0)        限幅验证：应读回 1200，**不会自己停**
 *   6   正转 1 s → 反转 2 s          换向时序验证，**最后平滑停**
 *   7   武装看门狗 + 保持 1200      **专验掉线保护**：不主动停车，3 秒后由
 *                                   `Motion_Tick()` 自己停；若一直转 = 掉线保护失效
 *
 * 关于"自己停"：`Motion_Drive(v, 0)` 的 holdMs=0 语义是"把速度设成 v 然后立刻返回"，
 * 它本体不负责停车；真正的三条停车路径是 ① 新命令覆盖 ② 掉线看门狗 ③ 急停。
 * 从调试器里 call 不走命令入口 App_ExecCmd，`Motion_NotifyAlive()` 不会被执行，
 * 看门狗（`Motion_Tick()` 开头的 `if (s_alive_ms == 0) return;`）因此完全不工作 ——
 * 所以 1/5 会一直转到断电。停车用 `Motion_Stop()`（立刻断脉冲）或 `Motion_Brake()`（平滑停）。
 *
 * 注意：
 *   - 自动动作发生在 App_Init() 末尾（READY 打印之后），此时四路电机
 *     和串口都已初始化完毕，等价于"上电就收到一条命令"；
 *   - 阻塞类动作（2/3/4/6）会让 App_Loop() 晚开始，期间不响应串口命令，
 *     这是预期行为，也正是 `D` 命令本来就有的特性；
 *   - **整车必须垫起（四轮悬空）之后再打开这个开关。**
 * ========================================================================== */

#ifndef CFG_DEBUG_AUTOTEST
#define CFG_DEBUG_AUTOTEST  0
#endif

#if (CFG_DEBUG_AUTOTEST != 0)
#warning "CFG_DEBUG_AUTOTEST != 0: 上电会自动驱动电机，调试完请改回 0"
#endif

#endif /* CFG_DEBUG_H */
