#ifndef CFG_MOTION_H
#define CFG_MOTION_H

/* S 曲线变速与运动安全参数
 *
 * 这里的所有常量都只被 App 层（motion.c）使用，
 * 改完重新编译即可，不需要改 CubeMX 工程。
 */

/* ---------------------------------------------------------------------------
 * S 曲线本身
 * ------------------------------------------------------------------------ */

/* 加速度（Hz/s）。变速时长 = |目标速度 - 当前速度| / 该值。
 * 1000 == "1200Hz 用 1200ms"，也就是每毫秒加 1Hz。
 * 例：0 → 1200Hz 需 1200ms；1200 → -1200Hz（跨 2400Hz）需 2400ms。
 * 运行时可改，不用重编译：Motion_SetAccel(hzPerSec)。
 *
 * 调试期取保守值：起步越柔和，瞬时电流越小、越不容易丢步。
 * 想更利落再往上加（2000 = 每毫秒 2Hz），但每次只加一档。 */
#define CFG_SCURVE_ACCEL_HZ_PER_S  1000

#define CFG_SCURVE_POINTS   101     /* 表长固定 101，改了两边都要改 */
#define CFG_SCURVE_SAMPLE_MS  8     /* 采样间隔：每 8ms 更新一次输出速度 */
#define CFG_SCURVE_MIN_MS    20     /* 变速时长下限，防止微小速度差也走长流程 */

/* ---------------------------------------------------------------------------
 * 安全限制（防止"发一条指令，车一直转"和"换向丢步"）
 * ------------------------------------------------------------------------ */

/* 软件速度上限（Hz，绝对值）。硬件上限是 cfg_motor.h 的 CFG_PUL_MAX_HZ，
 * 这里再压一道，保证上位机发 F99999 也只跑到这个值。
 *
 * **调试期保守档：1200Hz @1600 细分 ≈ 45rpm**（俯仰/转向都够看趋势，不够满载跑）。
 * 上机顺序：1200 跑通（不丢步、不过载、急停有效、3 秒自动停）→ 2000 → 3000，
 * 每上一档先空载、再带轮、再落地，别一次跳两级。
 * 提档只改这一行，其他代码不用动。 */
#define CFG_MOTION_MAX_SPEED_HZ    1200

/* 单段动作最长运行时间（ms）。holdMs 超过它就按它截断，
 * 防止一条指令把主循环卡住几分钟。0 表示不限制（不建议）。 */
#define CFG_MOTION_MAX_RUN_MS      5000

/* 上位机命令看门狗（ms）：收到运动类命令后开始计时，
 * 超过这个时间没有新命令就自动停车（掉线保护/死人开关）。
 * 持续行驶时上位机需要每隔 < 该值 的时间重发一次速度命令。 */
#define CFG_CMD_TIMEOUT_MS         3000

/* 换向时的"停顿"时间（ms）：先把脉冲降到 0 停住，等 DIR 电平建立
 * 再往反方向发脉冲。M860D 手册要求 DIR 至少提前 PUL 下降沿 5µs，
 * 300ms 远远足够，同时让机械有个缓冲。 */
#define CFG_MOTION_DIR_SETTLE_MS   300

#endif /* CFG_MOTION_H */
