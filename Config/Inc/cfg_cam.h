#ifndef CFG_CAM_H
#define CFG_CAM_H

/* ============================================================================
 * 相机端口参数（X5）—— 目前**还没接相机**，这里只把将来会用到的常数定下来
 *
 * 背景（README §9 的 C1-C5）：
 *   计划用 K230 / OpenMV 这类能自己跑识别的相机，通过第二路串口把
 *   "目标在哪、多大、识别到了没有"以短帧形式发给主控。主控只做运动，
 *   不做图像处理 —— 这样主循环的计算量可控，脉冲时序不会被拖坏。
 *
 * 定这些常数的目的：
 *   以后真正接相机时，只需要在 App 层写"帧 → 动作"的映射，
 *   物理参数（波特率/帧长上限/超时/量纲换算）全在这里改，不用翻代码。
 *
 * ⚠️ 换成正式相机后，下面带"待实测"的三条要按实际标定值改。
 * ============================================================================ */

/* ---- 物理层 ---- */
#define CFG_CAM_UART_BAUD          115200u /* 相机串口波特率（K230/OpenMV 常用值） */
#define CFG_CAM_RX_BUF_SIZE        64u     /* 单帧最大字节数：坐标 + 标志位足够，
                                            * 超过这个长度的帧直接丢弃并计错 */

/* ---- 时序 ---- */
#define CFG_CAM_TIMEOUT_MS         200u    /* 多久没收到相机帧就认为"相机失联"：
                                            * 失联后必须停车，不能拿着过期的坐标继续走 */
#define CFG_CAM_FRAME_PERIOD_MS    50u     /* 相机正常发帧周期（20 fps）—— 用它判断
                                            * "帧是新的还是旧的" */

/* ---- 坐标量纲（待实测标定）---- */
/* 像素 → 毫米的换算：用整数分子/分母，避免浮点（Cortex-M4 有 FPU，但
 * 中断里用浮点要注意上下文保存，整数最稳）。例：1 px = 0.35 mm → 35/100 */
#define CFG_CAM_MM_PER_PX_NUM      35u     /* 待实测 */
#define CFG_CAM_MM_PER_PX_DEN      100u    /* 待实测 */

/* 图像中心到车体中心的偏移（像素），用于把画面偏差换成横向纠偏量 */
#define CFG_CAM_CENTER_OFFSET_PX   0       /* 待实测：装好相机后标一次 */

/* ---- 目标判据 ---- */
#define CFG_CAM_TARGET_MIN_AREA    200u    /* 目标框小于这个像素面积就算"没看见"，
                                            * 防止把噪点当目标 */
#define CFG_CAM_LOST_FRAMES        3u      /* 连续丢几帧才判定目标丢失（去抖） */

#endif /* CFG_CAM_H */
