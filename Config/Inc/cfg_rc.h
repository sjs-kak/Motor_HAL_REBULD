#ifndef CFG_RC_H
#define CFG_RC_H

/* ============================================================================
 * 遥控（FS-i6X 发射机 + FS-iA6B 接收机）参数
 *
 * 本文件是**两套遥控输入方案的合成版**（2026-10-30 集成）：
 *
 *   CFG_RC_SOURCE_IBUS  ← 默认。USART3 + PB11，读 SERVO i-BUS 串行总线。
 *                          优点是只需要一根信号线、14 个通道、抗干扰好；
 *                          缺点是没有可靠的"射频丢失"标志，必须靠 CH5 开关
 *                          的 failsafe 位置兜底（见下面的 CFG_RC_ENABLE_*）。
 *
 *   CFG_RC_SOURCE_PWM   ← 备选。TIM3_CH1 + PA6 输入捕获，读 PPM/CPPM 单线。
 *                          优点是不依赖串口、时序完全可见；
 *                          缺点是占一个定时器通道，且只能收到 6 个通道。
 *
 * 两套的**引脚/外设/AF/极性**全部在 Bsp/Inc/mx_board.h，本文件只管常量。
 * 切换方案只需要改下面这一个宏，两套代码都保留在树里，不动一行就能换回去。
 *
 * ⚠️ 同一台硬件上两套**不能同时开**：PB11 与 PA6 虽然不冲突，但接收机
 *    只有一路输出，接哪根线就用哪套。开了 IBUS 就不要把信号线接 PA6。
 * ============================================================================ */

/* ---------------------------------------------------------------------------
 * 输入源选择：二选一，默认 i-BUS
 * ------------------------------------------------------------------------ */
#define CFG_RC_SOURCE_IBUS       1
#define CFG_RC_SOURCE_PWM        0

#if ((CFG_RC_SOURCE_IBUS != 0) && (CFG_RC_SOURCE_PWM != 0))
#error "CFG_RC_SOURCE_IBUS 与 CFG_RC_SOURCE_PWM 只能开一个：接收机只有一路输出"
#endif
#if ((CFG_RC_SOURCE_IBUS == 0) && (CFG_RC_SOURCE_PWM == 0))
#error "遥控输入源一个都没开：App_Loop 里不会有任何遥控数据"
#endif

/* ============================================================================
 * 一、i-BUS 方案的参数（CFG_RC_SOURCE_IBUS = 1 时生效）
 * ============================================================================ */
#if (CFG_RC_SOURCE_IBUS != 0)

/* 通道分配。本发射机 2026-10-27 实测：右摇杆垂直 = CH3，左摇杆水平 = CH4。
 * 通道号是 ONE based（1..14），与 rc_control.c 里的 0..13 下标差 1。
 * ⚠️ 换模型/换手（Mode 1↔2）后必须重新实测，否则"推前进变成转弯"。 */
#define CFG_RC_THROTTLE_CH          3U
#define CFG_RC_STEERING_CH          4U
#define CFG_RC_ENABLE_CH            5U   /* 分配 SWA；failsafe MUST be 1000 */
#define CFG_RC_THROTTLE_REVERSE     0U
#define CFG_RC_STEERING_REVERSE     0U

/* 摇杆行程（µs）。i-BUS 原生就是 µs 量纲，1000/1500/2000 是标准 Mode 2 行程。 */
#define CFG_RC_INPUT_MIN_US         1000U
#define CFG_RC_INPUT_CENTER_US      1500U
#define CFG_RC_INPUT_MAX_US         2000U

/* "这一帧可信"的宽范围：超出 [900, 2100] 认为接收机给了垃圾值，丢弃该帧。 */
#define CFG_RC_INPUT_VALID_MIN_US   900U
#define CFG_RC_INPUT_VALID_MAX_US   2100U

/* 中位死区：±50µs 内当 0，防止摇杆回中时的抖动导致车"爬行"。
 * 与 PWM 方案的 30µs 不同是故意的：i-BUS 的量化台阶更粗（约 10µs/LSB），
 * 死区太小会有一两个台阶的残余速度，静置时车会缓慢蹭动。 */
#define CFG_RC_DEADBAND_US          50U

/* CH5（SWA）作为"使能开关"的判据：
 *   < 1200µs  → 视为 LOW（待命，允许上电/解锁）
 *   > 1800µs  → 视为 HIGH（武装）
 *   中间      → 视为"不确定"，状态机保持等待，不冒险
 * failsafe 必须设成 LOW，这样射频一丢，开关自动回到"待命"，车停。 */
#define CFG_RC_ENABLE_LOW_US        1200U
#define CFG_RC_ENABLE_HIGH_US       1800U

/* 帧超时：超过这么久没有有效帧就认为信号丢了（i-BUS 帧率约 70Hz，200ms 约 14 帧）。 */
#define CFG_RC_FRAME_TIMEOUT_MS     200U

/* 解锁流程：必须先回中并稳住这么久，才允许从"待命"进"可行驶"。 */
#define CFG_RC_NEUTRAL_HOLD_MS      500U

/* 判"连续回中"时允许的帧间最大间隔：中间断档超过它就重新计时。 */
#define CFG_RC_NEUTRAL_MAX_GAP_MS   50U

/* 摇杆满量程对应的车速（Hz）。1000 = 满杆跑 CFG_RC_MAX_SPEED_HZ。 */
#define CFG_RC_MAX_SPEED_HZ         2500

/* 零油门时的转向地板：原地转向时两侧速度取 ±该值，避免"油门 0 就转不动"。
 * 它同时也是低油门时转向权重的下限。填 0 表示关掉这个地板。 */
#define CFG_RC_PIVOT_MAX_HZ         600

/* 状态日志的最小间隔（ms）：状态不变时也按这个周期打一行，方便现场观察。 */
#define CFG_RC_LOG_PERIOD_MS        500U

#endif /* CFG_RC_SOURCE_IBUS */

/* ============================================================================
 * 二、PWM / PPM 单线方案的参数（CFG_RC_SOURCE_PWM = 1 时生效）
 *
 * ⚠️ 本方案在集成时**保持阶段 A 的定位**：只采集、只打印，不驱动电机。
 *    它自己有一套 CFG_RC_DRIVE_ENABLE 开关，默认 0；打开会直接编译报错，
 *    这是故意的 —— 想让 PPM 驱动电机，必须先看完 app_rc.c 的待办并
 *    把"摇杆 → Motion_SetTarget"的映射补上。
 * ============================================================================ */
#if (CFG_RC_SOURCE_PWM != 0)

#include "cfg_motor.h"          /* CFG_TIM2_CLK_HZ：TIM3 与 TIM2 同在 APB1 */

/* ---------------------------------------------------------------------------
 * 时基：1 µs 分辨率
 *
 *   为什么必须是整数分频：
 *     计数频率 = APB1定时器时钟 / (PSC+1)。取 1 MHz 后，捕获值就是"多少 µs"，
 *     一帧 PPM 最长约 22.5 ms，16 位计数器(65535µs=65.5ms)装得下 ——
 *     所以**不需要溢出中断，也不需要软件扩位**，一个 u16 差值就够。
 *
 *   为什么 1 µs 够：通道脉宽 1000~2000 µs，分辨 1 µs = 0.1% 满量程，
 *     1200 档的两侧差速完全够用。再细就得上 0.25 µs，没必要。
 * ------------------------------------------------------------------------ */
#define CFG_RC_APB1_TIM_CLK_HZ   CFG_TIM2_CLK_HZ
#define CFG_RC_TICK_HZ           1000000UL
#define CFG_RC_TIM_PSC           ((CFG_RC_APB1_TIM_CLK_HZ / CFG_RC_TICK_HZ) - 1UL)

#if ((CFG_RC_APB1_TIM_CLK_HZ % CFG_RC_TICK_HZ) != 0UL)
#error "CFG_RC_TICK_HZ 不能整除 APB1 定时器时钟：µs 换算会不整，串口读数整体偏"
#endif
#if (CFG_RC_TIM_PSC > 65535UL)
#error "CFG_RC_TIM_PSC 超过 16 位，会被静默截断，µs 读数全错"
#endif

/* ---------------------------------------------------------------------------
 * 帧格式（PPM / CPPM）
 *
 *   上升沿之间量"槽宽"：同步头之后第 1 个槽 = CH1，依次到 CHn。
 *     槽宽 1000~2000 µs  → 一个通道的值（记住：这是槽宽，不是高电平宽度）
 *     槽宽 > 2500 µs     → 帧同步头，它后面那个才是 CH1
 *
 *   典型 6 通道：6×~1500 = 9 ms + 同步头 ~13.5 ms = 一帧 ~22.5 ms (≈45Hz)
 * ------------------------------------------------------------------------ */
#define CFG_RC_CH_NUM            6u      /* FS-iA6B 的 6 个通道 */
#define CFG_RC_SYNC_US           2500u   /* >= 此值判为同步头（正常最大槽 2000+余量）*/
#define CFG_RC_MIN_PULSE_US      300u    /* < 此值判为毛刺，丢弃（正常最小槽 1000）*/
#define CFG_RC_IC_FILTER         6u      /* 输入滤波 N=8 个采样 ≈95ns，滤掉线上毛刺 */

#if (CFG_RC_CH_NUM < 1u) || (CFG_RC_CH_NUM > 16u)
#error "CFG_RC_CH_NUM 不合理"
#endif
#if (CFG_RC_SYNC_US <= 2100u)
#error "CFG_RC_SYNC_US 必须大于最大通道槽宽(2000µs)，否则把一个通道误判成同步头"
#endif
#if (CFG_RC_MIN_PULSE_US >= 1000u)
#error "CFG_RC_MIN_PULSE_US 必须小于最小通道槽宽(1000µs)，否则真通道被当毛刺丢掉"
#endif

/* ---------------------------------------------------------------------------
 * 通道值语义（阶段 A 只用于打印与判读，阶段 B 才参与映射）
 * ------------------------------------------------------------------------ */
#define CFG_RC_MID_US            1500u   /* 中位 */
#define CFG_RC_HALF_SPAN_US      500u    /* 满量程半幅：1000/2000 就是 ±500 */

/* 信号丢失判定（同一毫秒）
 * 超过这个时间没有任何捕获沿 = 接收机没信号/线掉了/发射机关了 */
#define CFG_RC_LOST_MS           100u

/* ---------------------------------------------------------------------------
 * 中断优先级
 *   本工程生效的 NVIC 分组是 GROUP_2（被 Core/Src/stm32f4xx_hal_msp.c 覆盖），
 *   抢占优先级只有 0~3 有效。取 2：比串口(1)低，比主循环高。
 *   别填 4 以上 —— 会被静默截断成 3 或更小。
 * ------------------------------------------------------------------------ */
#define CFG_RC_IRQ_PRIORITY      2u

/* ---------------------------------------------------------------------------
 * 阶段开关
 *   0 = 阶段 A：只采集、只打印，一行都不碰 motion.c / 电机
 *   1 = 阶段 B：驱动电机（**尚未实现**，打开会编译报错，这是故意的）
 *
 *   为什么要用编译期开关而不是运行期模式：
 *     多人并行开发时，另一个人正在改运动控制程序。开关放在编译期，
 *     阶段 A 编出来的固件里根本不存在"摇杆 → 电机"的代码路径，
 *     物理上不可能互相干扰。
 * ------------------------------------------------------------------------ */
#define CFG_RC_DRIVE_ENABLE      0

#endif /* CFG_RC_SOURCE_PWM */

#endif /* CFG_RC_H */
