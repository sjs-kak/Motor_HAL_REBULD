# ============================================================================
#  build.ps1 - build from the command line (no VS Code extension needed)
#
#  Usage (from anywhere):
#     .\tools\build.ps1                  # incremental Debug build
#     .\tools\build.ps1 -Clean           # wipe build\Debug and rebuild
#     .\tools\build.ps1 -Preset Release  # Release build
#     .\tools\build.ps1 -ConfigOnly      # configure only (after CMakeLists edits)
#
#  Equivalent to:  cmake --preset Debug ; cmake --build --preset Debug
#  The script only locates the cmake/ninja/gcc that ship with the
#  STM32Cube VS Code extension, so you do not have to edit PATH yourself.
#
#  NOTE: keep this file ASCII-only. Windows PowerShell 5.1 reads .ps1 as the
#        ANSI code page (936 on a Chinese system) and non-ASCII text breaks it.
# ============================================================================
param(
    [ValidateSet('Debug', 'Release')]
    [string]$Preset = 'Debug',
    [switch]$Clean,
    [switch]$ConfigOnly
)

$ErrorActionPreference = 'Stop'
$Root     = Split-Path -Parent $PSScriptRoot          # tools\ -> project root
$BuildDir = Join-Path $Root "build\$Preset"
$Cache    = Join-Path $BuildDir 'CMakeCache.txt'

function Find-Tool([string]$Name) {
    $cmd = Get-Command $Name -ErrorAction SilentlyContinue
    if ($cmd) { return $cmd.Source }

    $bundles = Join-Path $env:LOCALAPPDATA 'stm32cube\bundles'
    if (Test-Path $bundles) {
        $hit = Get-ChildItem $bundles -Recurse -Filter $Name -File -ErrorAction SilentlyContinue |
               Sort-Object FullName -Descending | Select-Object -First 1
        if ($hit) { return $hit.FullName }
    }
    throw "Cannot find $Name - install the STM32Cube VS Code extension or add it to PATH."
}

# Prefer the exact tool recorded in the existing build dir, so we never mix
# cmake versions against a cache generated by another one.
function Get-CachedTool([string]$Key) {
    if (-not (Test-Path $Cache)) { return $null }
    $line = Select-String -Path $Cache -Pattern "^${Key}:[^=]*=(.+)$" | Select-Object -First 1
    if (-not $line) { return $null }
    $p = $line.Matches[0].Groups[1].Value.Trim()
    if ($p -and (Test-Path $p)) { return $p }
    return $null
}

if ($Clean -and (Test-Path $BuildDir)) {
    Write-Host "Removing $BuildDir ..." -ForegroundColor Yellow
    Remove-Item $BuildDir -Recurse -Force
}

$cmake = Get-CachedTool 'CMAKE_COMMAND'
if (-not $cmake) { $cmake = Find-Tool 'cmake.exe' }
$ninja = Get-CachedTool 'CMAKE_MAKE_PROGRAM'
if (-not $ninja) { $ninja = Find-Tool 'ninja.exe' }

# The toolchain file expects arm-none-eabi-gcc on PATH. Without this, a build
# dir that has just been wiped (-Clean, or a moved/renamed workspace) cannot
# even configure, because the cached absolute compiler path is gone.
$gcc = Get-CachedTool 'CMAKE_C_COMPILER'
if (-not $gcc) { $gcc = Find-Tool 'arm-none-eabi-gcc.exe' }

# The Ninja generator needs ninja.exe on PATH.
$env:PATH = (Split-Path $gcc -Parent) + ';' + (Split-Path $ninja -Parent) + ';' + (Split-Path $cmake -Parent) + ';' + $env:PATH

Push-Location $Root
try {
    if (-not (Test-Path $Cache)) {
        Write-Host "Configure: cmake --preset $Preset" -ForegroundColor Cyan
        & $cmake '--preset' $Preset
        if ($LASTEXITCODE -ne 0) { throw "configure failed (exit $LASTEXITCODE)" }
    }

    if (-not $ConfigOnly) {
        Write-Host "Build: cmake --build --preset $Preset" -ForegroundColor Cyan
        & $cmake '--build' '--preset' $Preset
        if ($LASTEXITCODE -ne 0) { throw "build failed (exit $LASTEXITCODE)" }

        $elf = Join-Path $BuildDir 'Motor_HAL_REBULD.elf'
        if (Test-Path $elf) {
            Write-Host ''
            Write-Host "OK -> $elf" -ForegroundColor Green
            & (Find-Tool 'arm-none-eabi-size.exe') $elf
        }
    }
}
finally {
    Pop-Location
}
